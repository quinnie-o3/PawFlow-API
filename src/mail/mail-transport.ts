import { randomUUID } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import type { ConfigService } from '@nestjs/config';
import { createTransport, type Transporter } from 'nodemailer';

/**
 * P3-BE02 minimal, replaceable e-mail delivery.
 *
 * The application depends only on `MailTransport`; the implementation is
 * chosen by `MAIL_TRANSPORT`:
 * - `disabled` (default): nothing is sent; a redacted notice is logged.
 * - `smtp`: nodemailer SMTP (`SMTP_HOST`, `SMTP_PORT`, `SMTP_SECURE`,
 *   `SMTP_USER`, `SMTP_PASSWORD`). Credentials come only from the environment.
 * - `file`: development/QA outbox. Each message is written as a JSON file to
 *   `MAIL_OUTBOX_DIR`. The files contain the links (and thus tokens), so this
 *   transport refuses to start when NODE_ENV=production.
 * Tests inject their own in-memory transport.
 */
export interface MailMessage {
  /** Template id, used for logging instead of the content. */
  category: 'PASSWORD_RESET' | 'EMAIL_VERIFICATION';
  to: string;
  subject: string;
  text: string;
  html: string;
}

export interface MailTransport {
  readonly name: string;
  send(message: MailMessage & { from: string }): Promise<void>;
}

export const MAIL_TRANSPORT = Symbol('MAIL_TRANSPORT');

export const DEFAULT_MAIL_FROM = 'PawFlow <no-reply@pawflow.local>';

export class DisabledMailTransport implements MailTransport {
  readonly name = 'disabled';

  send(): Promise<void> {
    return Promise.resolve();
  }
}

export class SmtpMailTransport implements MailTransport {
  readonly name = 'smtp';

  constructor(private readonly transporter: Pick<Transporter, 'sendMail'>) {}

  async send(message: MailMessage & { from: string }): Promise<void> {
    await this.transporter.sendMail({
      from: message.from,
      to: message.to,
      subject: message.subject,
      text: message.text,
      html: message.html,
      // Content is generated by the application; never resolve files/URLs.
      disableFileAccess: true,
      disableUrlAccess: true,
    });
  }
}

export class FileMailTransport implements MailTransport {
  readonly name = 'file';

  constructor(private readonly directory: string) {
    mkdirSync(directory, { recursive: true });
  }

  send(message: MailMessage & { from: string }): Promise<void> {
    const file = join(this.directory, `${Date.now()}-${randomUUID()}.json`);

    writeFileSync(file, JSON.stringify({ ...message, sentAt: new Date().toISOString() }, null, 2), {
      mode: 0o600,
    });

    return Promise.resolve();
  }
}

function flag(value: string | undefined): boolean {
  return value === 'true' || value === '1';
}

export function createMailTransport(config: ConfigService): MailTransport {
  const kind = (config.get<string>('MAIL_TRANSPORT') ?? 'disabled').trim().toLowerCase();

  switch (kind) {
    case 'disabled':
    case '':
      return new DisabledMailTransport();

    case 'file': {
      if (config.get<string>('NODE_ENV') === 'production') {
        throw new Error('MAIL_TRANSPORT=file is not allowed when NODE_ENV=production');
      }

      return new FileMailTransport(resolve(config.getOrThrow<string>('MAIL_OUTBOX_DIR')));
    }

    case 'smtp': {
      // Misconfiguration fails at startup instead of on the first e-mail.
      // Error messages name the variable, never its value.
      const user = config.get<string>('SMTP_USER');
      const password = config.get<string>('SMTP_PASSWORD');
      const port = Number(config.get<string>('SMTP_PORT') ?? 587);

      if (!Number.isInteger(port) || port < 1 || port > 65535) {
        throw new Error('SMTP_PORT must be an integer between 1 and 65535');
      }

      if (user && !password) {
        throw new Error('SMTP_PASSWORD is required when SMTP_USER is set');
      }

      return new SmtpMailTransport(
        createTransport({
          host: config.getOrThrow<string>('SMTP_HOST'),
          port,
          // true = TLS from the start (465); false = STARTTLS upgrade when offered.
          secure: flag(config.get<string>('SMTP_SECURE')),
          requireTLS: flag(config.get<string>('SMTP_REQUIRE_TLS')),
          auth: user ? { user, pass: password } : undefined,
          connectionTimeout: 10_000,
          greetingTimeout: 10_000,
          socketTimeout: 20_000,
        }),
      );
    }

    default:
      throw new Error(`Unsupported MAIL_TRANSPORT "${kind}" (expected disabled, smtp or file)`);
  }
}
